// Atribuição

/*   
    = Atribuição simples (comum)
    += Atribuição de adição
    -= Atribuição de subtração
    *= Atribuição de multiplicação
    /= Atribuição de divisão
    %= Atribuição de resto
*/
// Se não for atribuição simples, deve ser usado com uma variável let.

let valor = 10; // Atribuição simples
console.log(valor);

valor += 7; // Atribuição de adição
console.log(valor);

valor -= 7; //Atribuição de subtração
console.log(valor);

valor *= 7; //Atribuição de multiplicação
console.log(valor);

valor /= 7; //Atribuição de divisão
console.log(valor);

valor %= 7; // Atribuição de resto
console.log(valor);