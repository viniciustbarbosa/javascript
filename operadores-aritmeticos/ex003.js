const minute = 60;
const hour = minute * 60;
const day = hour * 24;
const week = day * 7;
const year = day * 365;

console.log(`1 minuto tem ${minute} segundos.`);
console.log(`1 hora tem ${hour} segundos.`);
console.log(`1 dia tem ${day} segundos.`);
console.log(`1 semana tem ${week} segundos.`);
console.log(`1 ano tem ${year} segundos.`);