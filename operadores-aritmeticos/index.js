//Operadores aritméticos

/* 
     +   Adição
    -   Subtração
    *   Multiplicação
    /   Divisão
    %   Resto da divisão
    **  Exponenciação
*/

//Soma

const x = 5;
const y = 2;

let result = x + y;

console.log(result);

//Subtração

result = x - y;

console.log(result);

//Multiplicação

result = x * y;

console.log(result);

//Divisão

result = x/y;

console.log(result);

//Resto da divisão (Serve para saber se um número é par ou ímpar, por exemplo)

result = x % y;

console.log(result);

//Exponenciação

result = x ** y;

console.log(result);